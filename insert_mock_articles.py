def main():
    """主函数"""
    print("正在连接数据库...")
    
    # 创建数据库引擎
    engine = create_engine(settings.DATABASE_URL)
    SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
    db = SessionLocal()
    
    try:
        print("\n开始插入模拟文章数据...")
        
        # 为每个分类插入文章
        for category, articles in category_articles.items():
            print(f"\n正在处理分类: {category}")
            
            for article_data in articles:
                print(f"  正在插入文章: {article_data['title']}")
                
                try:
                    # 插入到数据库
                    db.execute(
                        text("""
                        INSERT INTO contents (title, content, category, summary, author_id, is_published, view_count, published_at, price, created_at, updated_at)
                        VALUES (:title, :content, :category, :summary, :author_id, :is_published, 0, NOW(), :price, NOW(), NOW())
                        """),
                        {
                            "title": article_data["title"],
                            "content": article_data["content"],
                            "category": category,
                            "summary": article_data["content"][:100] + "...",
                            "author_id": 1,  # 默认作者ID
                            "is_published": True,
                            "price": random.uniform(5.9, 19.9)
                        }
                    )
                    
                    db.commit()
                    print(f"  ✓ 成功插入文章: {article_data['title']}")
                    
                except Exception as e:
                    print(f"  ✗ 插入文章失败: {e}")
                    db.rollback()
                    continue
        
        print("\n所有模拟文章数据插入完成！")
        
    except Exception as e:
        print(f"\n发生错误: {e}")
        db.rollback()
    finally:
        db.close()

if __name__ == "__main__":
    main()
